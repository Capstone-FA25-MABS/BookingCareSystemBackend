/// Represents the role of a blog author.
/// </summary>
public enum BlogAuthorRole
{
    /// <summary>
    /// The main author of the blog.
    /// </summary>
    AUTHOR,
    /// <summary>
    /// The reviewer of the blog content.
    /// </summary>
    REVIEWER,
    /// <summary>
    /// The advisor for the blog content.
    /// </summary>
    ADVISOR
}